  /**
   * Fallback-safe translation resolver.
   * If a string is blank or missing in Hindi/Gujarati, gracefully falls back to English.
   * Never shows raw translation key names to the farmer.
   */
  fun safeTranslate(value: String?, fallback: String): String {
    return if (value.isNullOrBlank()) fallback else value
  }
